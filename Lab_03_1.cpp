#include <iostream>
#include <cmath>

using namespace std;

int main()
{
    double x;  // вхідний аргумент
    double y;  // результат обчислення виразу
    double B;  // функціонально змінна частина виразу
    double A;  // функціонально стала частина виразу

    cout << "x = "; cin >> x;

    A = x * x + sin(4.0 * x / 3.0);

    // Спосіб 1: розгалуження в скороченій формі
    if (x < -5.0)
        B = 1.0 / tan(x);
    if (x >= -5.0 && x <= 0.0)
        B = 4.0 - (x * x) / 2.0;
    if (x > 0.0)
        B = log10(x * x) - (4.0 * x) / 3.0;

    y = A + B;
    cout << endl;
    cout << "1) y = " << y << endl;

    // Спосіб 2: розгалуження в повній формі
    if (x < -5.0)
        B = 1.0 / tan(x);
    else
        if (x <= 0.0)
            B = 4.0 - (x * x) / 2.0;
        else
            B = log10(x * x) - (4.0 * x) / 3.0;

    y = A + B;
    cout << "2) y = " << y << endl;

    cin.get();
    return 0;
}
